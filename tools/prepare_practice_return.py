"""Render Custom Practice completion labels using the menu label renderer."""
from pathlib import Path
import sys
from PIL import Image
from render_ui_label import render_label

ROOT = Path(__file__).resolve().parent.parent
SECONDS = 10


def prepare(font, title01):
    sheet = Image.new('RGBA', (512, 1024))
    labels = []
    texts = []
    for language in range(2):
        for retry in range(2):
            for seconds in range(1, SECONDS + 1):
                if language == 0:
                    verb = 'Retrying' if retry else 'Returning'
                    text = f'{verb} in {seconds} second' + ('s' if seconds != 1 else '')
                else:
                    text = f'{seconds}秒後に' + ('再挑戦します' if retry else '設定画面へ戻ります')
                texts.append((text, 16, 1))
    choice_start = len(texts)
    for text in ('Retry Spell Card', 'Return to Practice', 'Return to Title', 'スペルカード再挑戦', '練習設定へ戻る', 'タイトルへ戻る'):
        texts.append((text, 22, 2))
    x = y = row_height = 0
    for text, size, stroke in texts:
        tile, _, _ = render_label(text, font, title01, size, stroke, 2)
        if tile.width > sheet.width:
            raise ValueError('Completion label exceeds its atlas width')
        if x + tile.width > sheet.width:
            x = 0
            y += row_height + 2
            row_height = 0
        if y + tile.height > sheet.height:
            raise ValueError('Completion labels exceed their atlas height')
        sheet.alpha_composite(tile, (x, y))
        labels.append((x, y, tile.width, tile.height))
        x += tile.width + 2
        row_height = max(row_height, tile.height)
    sheet.save(ROOT/'tools/converter/resources/practice-return.png')
    header = ['#pragma once', '// Generated by tools/prepare_practice_return.py.',
              'namespace CtrPracticeReturnAssets {', 'struct Label {int x,y,w,h;};',
              f'inline constexpr int ChoiceStart={choice_start};', 'inline constexpr Label labels[]={']
    header += ['{%d,%d,%d,%d},' % label for label in labels]
    header += ['};', '}', '']
    (ROOT/'assets/practice_return.hpp').write_text('\n'.join(header), encoding='utf-8')


if __name__ == '__main__':
    prepare(Path(sys.argv[1]), Path(sys.argv[2]))
