"""Write src/practice/Th06CatalogJa.hpp: Japanese names for Th06Catalog.hpp.

Usage:
    python tools/build_practice_ja.py <thprac_games_def.json>

thprac_games_def.json is thprac's game definition (src/thprac_games_def.json in
https://github.com/touhouworldcup/thprac). Each section there carries its
Chinese, English and Japanese names per difficulty group; this pairs every
catalog entry with its group by id and difficulty and checks that thprac's
English name is the catalog's before taking the Japanese one.
"""
from pathlib import Path
import json
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT/'src/practice/Th06Catalog.hpp'
OUT = ROOT/'src/practice/Th06CatalogJa.hpp'
LETTERS = {'E': 1, 'N': 2, 'H': 4, 'L': 8, 'X': 16}
# Phase names of the two multi-phase Extra spells, as thprac's glossary words them.
PHASES = {'Phase 1': 'フェーズ1', 'Phase 2': 'フェーズ2', 'Finale': '最終フェーズ',
          'Normal': '通常', '30% Health Left': '体力30%から', 'Rage': '発狂'}
ENTRY = re.compile(r'\{"(TH06_\w+)","((?:[^"\\]|\\.)*)",(\d+),(-?\d+),(\d+),(\d+),(-?\d+),(\w+),(\w+),\{([^}]*)\}\}')


def main(definition):
    data = json.loads(Path(definition).read_text(encoding='utf-8'))
    glossary = {**data['common']['glossary'], **data['th06']['glossary']}
    sections = data['th06']['sections']
    names, phases = [], []
    for match in ENTRY.finditer(CATALOG.read_text(encoding='utf-8')):
        # The catalog writes non-ASCII letters as C++ \uXXXX escapes.
        english = re.sub(r'\\u([0-9a-fA-F]{4})', lambda u: chr(int(u.group(1), 16)), match.group(2).replace('\\"', '"'))
        key, mask = match.group(1), int(match.group(5))
        section = sections[key]
        group = next((value for name, value in section.items() if name.startswith('!') and
                      sum(LETTERS[c] for c in name[1:]) & mask == mask), None)
        if group is None:
            raise ValueError(f'{key}: no thprac name for difficulty mask {mask}')
        words = glossary[group] if isinstance(group, str) else group
        # thprac breaks a few long names over two lines.
        if ' '.join(words[1].split()) != english:
            raise ValueError(f'{key}: thprac names "{words[1]}", the catalog "{english}"')
        names.append(''.join(words[2].split('\n')))
        phases.append([PHASES[p.strip().strip('"')] for p in match.group(10).split(',') if p.strip()])
    lines = ['#pragma once', '// Generated by tools/build_practice_ja.py from thprac\'s game definition.',
             '// Japanese names of Th06Catalog.hpp\'s entries, in the same order.',
             'namespace Practice::Th06 {', 'inline const char* const CatalogJa[]={']
    lines += [f'    "{name}",' for name in names]
    lines += ['};', '// Japanese phase names of entries with phases, by catalog index.',
              'struct PhasesJa {int entry;const char* names[3];};', 'inline const PhasesJa CatalogPhasesJa[]={']
    lines += ['    {%d,{%s}},' % (i, ','.join(f'"{p}"' for p in entry)) for i, entry in enumerate(phases) if entry]
    lines += ['};', '}']
    OUT.write_text('\n'.join(lines)+'\n', encoding='utf-8')
    print(len(names), 'entries')


if __name__ == '__main__':
    main(sys.argv[1])
